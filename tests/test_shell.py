def test_shell_install_upgrades_valid_v060_wrapper_in_place(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    ccs_path, claude_path = _trusted_binaries(tmp_path, monkeypatch)
    zdotdir = tmp_path / "zsh"
    zdotdir.mkdir()
    rc = zdotdir / ".zshrc"
    monkeypatch.setenv("ZDOTDIR", str(zdotdir))
    store = ProfileStore(tmp_path / "store")
    script = store.home / "claude.zsh"
    old_contents = _v060_source_script(ccs_path, claude_path)
    script.write_text(old_contents)
    script.chmod(0o600)
    prefix = "export BEFORE=1\n"
    suffix = "\nexport AFTER=1\n"
    old_digest = hashlib.sha256(old_contents.encode()).hexdigest()
    rc.write_text(prefix + _managed_block(script, "yes", old_digest) + suffix)
    rc.chmod(0o600)

    assert installed(store)
    install(store)

    new_contents = _source_script(ccs_path, claude_path)
    new_digest = hashlib.sha256(new_contents.encode()).hexdigest()
    assert script.read_text() == new_contents
    assert rc.read_text() == prefix + _managed_block(script, "yes", new_digest) + suffix
    assert installed(store)
    uninstall(store)
    assert rc.read_text() == prefix + suffix[1:]
    assert not script.exists()


def test_shell_install_recovers_interrupted_wrapper_upgrade(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    ccs_path, claude_path = _trusted_binaries(tmp_path, monkeypatch)
    zdotdir = tmp_path / "zsh"
    zdotdir.mkdir()
    rc = zdotdir / ".zshrc"
    monkeypatch.setenv("ZDOTDIR", str(zdotdir))
    store = ProfileStore(tmp_path / "store")
    script = store.home / "claude.zsh"
    old_contents = _v060_source_script(ccs_path, claude_path)
    old_digest = hashlib.sha256(old_contents.encode()).hexdigest()
    rc.write_text(_managed_block(script, "no", old_digest) + "\n")
    rc.chmod(0o600)
    # State left behind if the process exited between the two atomic writes.
    new_contents = _source_script(ccs_path, claude_path)
    script.write_text(new_contents)
    script.chmod(0o600)

    install(store)

    assert installed(store)
    assert script.read_text() == new_contents
    assert hashlib.sha256(new_contents.encode()).hexdigest() in rc.read_text()


def test_shell_install_refuses_tampered_managed_script_during_upgrade(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    ccs_path, claude_path = _trusted_binaries(tmp_path, monkeypatch)
    zdotdir = tmp_path / "zsh"
    zdotdir.mkdir()
    rc = zdotdir / ".zshrc"
    monkeypatch.setenv("ZDOTDIR", str(zdotdir))
    store = ProfileStore(tmp_path / "store")
    script = store.home / "claude.zsh"
    old_contents = _v060_source_script(ccs_path, claude_path)
    old_digest = hashlib.sha256(old_contents.encode()).hexdigest()
    script.write_text(old_contents)
    script.chmod(0o600)
    original_rc = (
        "export USER_SETTING=kept\n"
        + _managed_block(script, "yes", old_digest)
        + "\n# after managed block\n"
    )
    rc.write_text(original_rc)
    rc.chmod(0o600)
    tampered = old_contents + "# local edit\n"
    script.write_text(tampered)

    with pytest.raises(RuntimeError, match="script was modified"):
        install(store)
    assert rc.read_text() == original_rc
    assert script.read_text() == tampered


def test_source_script_does_not_resubstitute_marker_inside_quoted_path(tmp_path: Path) -> None:
    binary_dir = tmp_path / "c c" / "__CLAUDE_BIN__"
    binary_dir.mkdir(parents=True)
    fake_ccs = binary_dir / "ccs"
    fake_ccs.write_text(
        "#!/bin/sh\n"
        "printf '%s\\n' \"$CC_SWAPER_CLAUDE_BIN\" > \"$CCS_LOG\"\n"
    )
    fake_ccs.chmod(0o755)
    suspicious_claude = tmp_path / "claude; echo INJECTED"
    wrapper = tmp_path / "wrapper.zsh"
    wrapper.write_text(_source_script(fake_ccs, suspicious_claude))
    log = tmp_path / "seen-path"
    env = dict(os.environ, CCS_LOG=str(log))

    result = subprocess.run(
        ["zsh", "-f", "-c", f"source {shlex.quote(str(wrapper))}; claude hello"],
        env=env, capture_output=True, text=True, timeout=5,
    )
    assert result.returncode == 0, result.stderr
    assert log.read_text().strip() == str(suspicious_claude)
    assert "INJECTED" not in result.stdout + result.stderr
