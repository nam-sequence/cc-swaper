def _trusted_binaries(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> tuple[Path, Path]:
    fake_bin = tmp_path / "trusted bin"
    fake_bin.mkdir()
    fake_ccs = fake_bin / "ccs"
    fake_ccs.write_text(
        "#!/usr/bin/env python3\n"
        "import json, os, sys\n"
        "with open(os.environ['CCS_LOG'], 'a') as h: h.write(json.dumps(sys.argv[1:]) + '\\n')\n"
        "with open(os.environ['CCS_BIN_LOG'], 'a') as h: h.write(os.environ.get('CC_SWAPER_CLAUDE_BIN', '') + '\\n')\n"
    )
    fake_ccs.chmod(0o755)
    fake_claude = fake_bin / "claude"
    fake_claude.write_text("#!/bin/sh\nexit 0\n")
    fake_claude.chmod(0o755)
    monkeypatch.setenv("PATH", f"{fake_bin}{os.pathsep}{os.environ['PATH']}")
    return fake_ccs.resolve(), fake_claude.resolve()


def _v060_source_script(ccs_path: Path, claude_path: Path) -> str:
    """Return the exact generated wrapper from the v0.6.0 release."""
    template = """# Generated by cc-swaper. Use `ccs shell uninstall` to remove.
# This function affects interactive Zsh only; scripts keep the native binary.
function claude() {
  local first="${1-}"
  local arg
  local -x CC_SWAPER_CLAUDE_BIN=__CLAUDE_BIN__
  case "$first" in
    auth|agents|attach|config|doctor|gateway|import|install|kill|logs|mcp|plugin|plugins|project|respawn|rm|setup-token|stop|ultrareview|update|upgrade)
      command __CCS_BIN__ native -- "$@"
      return $?
      ;;
  esac
  if [[ "$first" == "-c" || "$first" == "--continue" ]] && [[ $# -eq 1 ]]; then
    command __CCS_BIN__ resume
    return $?
  fi
  if [[ "$first" == "-r" || "$first" == "--resume" ]] && [[ $# -eq 2 ]]; then
    command __CCS_BIN__ resume "$2"
    return $?
  fi
  for arg in "$@"; do
    case "$arg" in
      -p|--print|--bg|--background|-c|--continue|-r|--resume|--help|-h|-v|--version)
        command __CCS_BIN__ native -- "$@"
        return $?
        ;;
    esac
  done
  command __CCS_BIN__ run -- "$@"
}
"""
    quoted = {
        "__CCS_BIN__": shlex.quote(str(ccs_path)),
        "__CLAUDE_BIN__": shlex.quote(str(claude_path)),
    }
    return re.sub(r"__CCS_BIN__|__CLAUDE_BIN__", lambda match: quoted[match.group()], template)


def test_shell_install_is_reversible_and_idempotent(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    ccs_path, claude_path = _trusted_binaries(tmp_path, monkeypatch)
    zdotdir = tmp_path / "zsh"
    zdotdir.mkdir()
    rc = zdotdir / ".zshrc"
    original = "export EXAMPLE=1\n"
    rc.write_text(original)
    rc.chmod(0o600)
    monkeypatch.setenv("ZDOTDIR", str(zdotdir))
    store = ProfileStore(tmp_path / "store")

    assert install(store) == rc
    assert installed(store)
    first = rc.read_text()
    assert "source " in first
    script = store.home / "claude.zsh"
    assert script.read_text() == _source_script(ccs_path, claude_path)
    assert 'command ' + shlex.quote(str(ccs_path)) + ' native -- "$@"' in script.read_text()
    assert install(store) == rc
    assert rc.read_text() == first
    assert (store.home / "claude.zsh").stat().st_mode & 0o777 == 0o600

    assert uninstall(store) == rc
    assert rc.read_text() == original
    assert not (store.home / "claude.zsh").exists()
    assert not installed(store)


def test_shell_wrapper_forwards_all_arguments_and_pins_claude_binary(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    fake_ccs, fake_claude = _trusted_binaries(tmp_path, monkeypatch)
    zdotdir = tmp_path / "zsh"
    zdotdir.mkdir()
    monkeypatch.setenv("ZDOTDIR", str(zdotdir))
    store = ProfileStore(tmp_path / "store")

    install(store)
    log = tmp_path / "calls.jsonl"
    bin_log = tmp_path / "claude-bins.txt"
    env = dict(os.environ)
    env.update({
        "ZDOTDIR": str(zdotdir),
        "CCS_LOG": str(log),
        "CCS_BIN_LOG": str(bin_log),
        "PATH": os.environ["PATH"],
    })
    result = subprocess.run(
        [
            "zsh", "-ic",
            "claude 'fix bug' --model 'sonnet 4' ''; claude auth status; "
            "claude -c; claude --print hi; claude --version; claude",
        ],
        env=env, capture_output=True, text=True, timeout=10,
    )
    assert result.returncode == 0, result.stderr
    calls = [json.loads(line) for line in log.read_text().splitlines()]
    assert calls == [
        ["native", "--", "fix bug", "--model", "sonnet 4", ""],
        ["native", "--", "auth", "status"],
        ["native", "--", "-c"],
        ["native", "--", "--print", "hi"],
        ["native", "--", "--version"],
        ["native", "--"],
    ]
    assert bin_log.read_text().splitlines() == [str(fake_claude)] * len(calls)
    script = (store.home / "claude.zsh").read_text()
    assert f"local -x CC_SWAPER_CLAUDE_BIN={shlex.quote(str(fake_claude))}" in script
    assert " native -- \"$@\"" in script
    assert " run -- " not in script
    assert " resume" not in script


